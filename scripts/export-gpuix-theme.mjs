#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(repoRoot, "tokens", "rizum-glass.tokens.json");
const outputPath = path.join(
  repoRoot,
  "adapters",
  "gpuix",
  "generated",
  "rizum-glass-tokens.ts",
);
const tokens = JSON.parse(fs.readFileSync(sourcePath, "utf8"));

function color(name) {
  const value = tokens.color?.[name]?.$value?.hex;
  if (!value) throw new Error(`Missing color token: ${name}`);
  return value.toUpperCase();
}

function length(group, name) {
  const token = tokens[group]?.[name]?.$value;
  if (!token || typeof token.value !== "number") {
    throw new Error(`Missing length token: ${group}.${name}`);
  }
  if (token.unit === "px") return token.value;
  if (token.unit === "rem") return token.value * 16;
  throw new Error(`Unsupported unit for ${group}.${name}: ${token.unit}`);
}

function fontSize(name) {
  const token = tokens.typography?.[name]?.$value?.fontSize;
  if (!token || typeof token.value !== "number") {
    throw new Error(`Missing typography token: ${name}`);
  }
  return token.unit === "rem" ? token.value * 16 : token.value;
}

const colorNames = [
  "ink", "ink-soft", "ink-muted", "caption", "canvas", "surface",
  "surface-muted", "surface-line", "dark-canvas", "dark-surface",
  "dark-surface-muted", "dark-surface-line", "dark-ink", "dark-ink-soft",
  "dark-ink-muted", "dark-caption", "accent-teal", "accent-cyan",
  "accent-orange", "accent-yellow", "accent-violet", "accent-rose", "accent-mint",
];
const lengthNames = {
  radius: ["xs", "sm", "md", "lg", "xl", "bubble", "full"],
  spacing: ["xs", "sm", "md", "lg", "xl", "xxl"],
};

const output = `// Generated by scripts/export-gpuix-theme.mjs. Do not edit by hand.\n\n` +
  `export const rizumGlass = ${JSON.stringify({
    stack: {
      runtime: "Bun + TypeScript + React 19 + @gpuix/react",
      renderer: "GPUI",
    },
    color: Object.fromEntries(colorNames.map((name) => [name, color(name)])),
    radius: Object.fromEntries(lengthNames.radius.map((name) => [name, length("rounded", name)])),
    spacing: Object.fromEntries(lengthNames.spacing.map((name) => [name, length("spacing", name)])),
    type: {
      display: fontSize("display-serif"),
      title: fontSize("title-serif"),
      subtitle: fontSize("subtitle-serif"),
      body: fontSize("body-ui"),
      label: fontSize("label-ui"),
      caption: fontSize("caption-caps"),
    },
    window: {
      outerCornerSource: "platform",
      controlOwnership: "system",
      windowsNormalRadiusEpx: 8,
      windowsExpandedRadiusEpx: 0,
      identityIconPx: 16,
      identityGapPx: 8,
    },
  }, null, 2)} as const;\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(`Exported ${path.relative(repoRoot, outputPath)}.`);
