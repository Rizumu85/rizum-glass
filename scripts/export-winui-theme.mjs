  name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const defaultBrushes = colorNames
  .map(
    (name) =>
      `      <SolidColorBrush x:Key="RizumBrush${colorKey(name)}" Color="{StaticResource RizumColor${colorKey(name)}}" />`,
  )
  .join("\n");

const highContrastBrushes = colorNames
  .map((name) => {
    let systemColor = "SystemColorWindowTextColor";
    if (["canvas", "surface", "surface-muted"].includes(name)) {
      systemColor = "SystemColorWindowColor";
    } else if (name === "surface-line") {
      systemColor = "SystemColorGrayTextColor";
    } else if (name.startsWith("accent-")) {
      systemColor = "SystemColorHighlightColor";
    }
    return `      <SolidColorBrush x:Key="RizumBrush${colorKey(name)}" Color="{ThemeResource ${systemColor}}" />`;
  })
  .join("\n");

const rawColors = colorNames
  .map(
    (name) =>
      `  <Color x:Key="RizumColor${colorKey(name)}">${argb(name)}</Color>`,
  )
  .join("\n");

const darkRawColors = colorNames
  .map(
    (name) =>
      `  <Color x:Key="RizumColor${colorKey(name)}">${darkArgb(name)}</Color>`,
  )
  .join("\n");

const display = type("display-serif");
const title = type("title-serif");
const subtitle = type("subtitle-serif");
const body = type("body-ui");
const dialogue = type("dialogue-body");
const label = type("label-ui");
const caption = type("caption-caps");
const mono = type("mono-note");

